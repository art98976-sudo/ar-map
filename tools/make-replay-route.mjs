// Phase 1: fetch the test route Library main entrance -> A3 Lecture Theatre (Cottrell, Level 2) once
// from MazeMap, fitted to MazeMap's floors exactly as the app does (planRoute), and save it as a
// fixture for the synthetic replays (tests/fixtures/route-library-a3.json). Generated data only.
//   node --dns-result-order=ipv4first tools/make-replay-route.mjs
import {writeFileSync} from 'node:fs'
import {createServer} from 'vite'

const LIBRARY_MAIN_ENTRANCE = {type: 'place', placeId: 'library', name: 'Library', entranceName: 'main entrance', lat: 56.145454, lng: -3.919805}
const A3 = {id: 'mm-1002085033', name: 'A3 Lecture Theatre', category: 'room', floor: 2, lat: 56.144797627811215, lng: -3.9205121464987616, mazemapPoi: 1002085033}

const server = await createServer({server: {middlewareMode: true}, appType: 'custom', logLevel: 'error'})
try {
  const {planRoute} = await server.ssrLoadModule('/src/route/route.js')
  const route = await planRoute(LIBRARY_MAIN_ENTRANCE, A3, {network: false, stepFree: false})
  if (route.status !== 'ok') throw new Error(`MazeMap gave no route: ${JSON.stringify(route).slice(0, 300)}`)
  if (!route.fitted?.sceneLoaded) throw new Error('The floors did not load: the route would not be fitted. Try again.')
  const {fitted, ...rest} = route
  const out = {
    note: 'Generated by tools/make-replay-route.mjs from MazeMap (planRoute, fitted to the floors). Do not edit by hand.',
    generatedAt: new Date().toISOString(),
    startPoint: LIBRARY_MAIN_ENTRANCE,
    destination: A3,
    route: {...rest, fittedDoors: fitted.doors, fittedLengthM: fitted.lengthM},
  }
  writeFileSync('tests/fixtures/route-library-a3.json', JSON.stringify(out, null, 1))
  const levels = [...new Set([...route.points, ...(route.indoorPoints ?? [])].map((p) => p.z))]
  console.log(`saved: ${route.points.length} outdoor + ${route.indoorPoints?.length ?? 0} indoor points, ${Math.round(route.totalM ?? route.lengthM)} m, levels ${levels.join(', ')}`)
} finally {
  await server.close()
}
