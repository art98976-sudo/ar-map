import {formatNumber} from '../i18n.js'

const TURN = {left: '左转', right: '右转', 'slight-left': '稍向左转', 'slight-right': '稍向右转'}
const distance = (m) => (m >= 1000 ? `${formatNumber(m / 1000, {decimals: 1})} 公里` : `${m <= 20 ? Math.round(m) : Math.round(m / 5) * 5} 米`)
const road = (info) => (info ? (info.beside ? `${info.road} 旁边的小路` : info.road) : null)
/** "在 The Bite 处", "朝 Library 方向": before the verb. */
const before = (m, alone = true) => (m?.landmark ? `在 ${m.landmark} 处` : '') + (m?.towards && alone ? `朝 ${m.towards} 方向` : '')
/** "，进入 Pathfoot Road": after the verb. */
const after = (info) => (info ? `，进入 ${road(info)}` : '')
/** "，走 20 米后再左转，进入 Pathfoot Road". */
const then = (m) => {
  if (!m.then) return ''
  const again = m.then.type === m.type ? '再次' : '再'
  return `，走 ${distance(m.then.gapM)}后${before(m.then)}${again}${TURN[m.then.type]}${after(m.ontoInfo)}${m.towards ? `，朝 ${m.towards} 方向走` : ''}`
}
const turn = (m) => `${before(m, !m.then)}${TURN[m.type] ?? '直行'}${m.then ? '' : after(m.ontoInfo)}${then(m)}`

export const DIRECTIONS = {
  distance,
  place: (name) => name,
  onto: road,
  banner(m, away, arriveLabel) {
    if (m.type === 'arrive') return away == null ? `已到达 ${arriveLabel}` : `前方 ${away}到达 ${arriveLabel}`
    if (away == null) return `${before(m, !m.then)}立即${TURN[m.type] ?? '直行'}${m.then ? '' : after(m.ontoInfo)}${then(m)}`
    return `前方 ${away}，${turn(m)}`
  },
  stepLine(m, arriveLabel) {
    if (m.type === 'arrive') return `到达 ${arriveLabel}`
    return turn(m)
  },
  detail(d) {
    if (!d) return null
    if (d.kind === 'follow') return `沿 ${d.beside ? `${d.road} 旁边的小路走` : `${d.road} 走`}${d.water ? `，途经 ${d.water}` : ''}`
    if (d.kind === 'water') return `沿 ${d.water} 旁边的小路走`
    if (d.kind === 'pass') return `经过${d.side === 'left' ? '左侧' : '右侧'}的 ${d.building}`
    return null
  },
  spoken: (detail, words) => `${detail}。${words}`,
  arCard(c) {
    if (c.kind === 'past') return `直行，经过 ${c.place} · ${c.away}`
    if (c.kind === 'continue') return `直行 ${c.away}`
    if (c.kind === 'arrive') return `${c.away}后到达 ${c.label}`
    if (c.landmark) return `在 ${c.landmark} 处${TURN[c.type]} · ${c.now ? '现在' : c.away}`
    return c.now ? `现在${TURN[c.type]}` : `${c.away}后${TURN[c.type]}`
  },
  arStep: (type, landmark) => `${landmark ? `在 ${landmark} 处` : ''}${TURN[type]}`,
}

