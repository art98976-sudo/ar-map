// t() does the same for every filled-in name. Western digits, as on the campus signs.
import {formatNumber} from '../i18n.js'

const iso = (text) => `⁨${text}⁩`
const TURN = {left: 'انعطف يسارًا', right: 'انعطف يمينًا', 'slight-left': 'انعطف قليلًا إلى اليسار', 'slight-right': 'انعطف قليلًا إلى اليمين'}
const THEN = {left: 'يسارًا', right: 'يمينًا', 'slight-left': 'قليلًا إلى اليسار', 'slight-right': 'قليلًا إلى اليمين'}
const distance = (m) => iso(m >= 1000 ? `${formatNumber(m / 1000, {decimals: 1})} كم` : `${m <= 20 ? Math.round(m) : Math.round(m / 5) * 5} م`)
const road = (info) => (info ? (info.beside ? `الممر بجانب ${iso(info.road)}` : iso(info.road)) : null)
/** " عند The Bite", " إلى Pathfoot Road", " باتجاه Library". */
const at = (m) => {
  const onto = road(m?.ontoInfo)
  return (m?.landmark ? ` عند ${iso(m.landmark)}` : '') + (onto && !m.then ? ` إلى ${onto}` : '') + (m?.towards && !m.then ? ` باتجاه ${iso(m.towards)}` : '')
}
/** "، ثم يسارًا بعد 20 م إلى Pathfoot Road". */
const then = (m) => {
  if (!m.then) return ''
  const again = m.then.type === m.type ? ' مرة أخرى' : ''
  const onto = road(m.ontoInfo)
  return `، ثم ${THEN[m.then.type]}${again}${at(m.then)} بعد ${distance(m.then.gapM)}${onto ? ` إلى ${onto}` : ''}${m.towards ? ` باتجاه ${iso(m.towards)}` : ''}`
}

export const DIRECTIONS = {
  distance,
  place: iso,
  onto: road,
  banner(m, away, arriveLabel) {
    if (m.type === 'arrive') return away == null ? `لقد وصلت إلى ${iso(arriveLabel)}` : `بعد ${away}، ستصل إلى ${iso(arriveLabel)}`
    if (away == null) return `${TURN[m.type] ?? 'تابع مباشرةً'} الآن${at(m)}${then(m)}`
    return `بعد ${away}، ${TURN[m.type] ?? 'تابع مباشرةً'}${at(m)}${then(m)}`
  },
  stepLine(m, arriveLabel) {
    if (m.type === 'arrive') return `الوصول إلى ${iso(arriveLabel)}`
    return `${TURN[m.type] ?? 'تابع مباشرةً'}${at(m)}${then(m)}`
  },
  detail(d) {
    if (!d) return null
    if (d.kind === 'follow') return `اتبع ${d.beside ? `الممر بجانب ${iso(d.road)}` : iso(d.road)}${d.water ? `، مرورًا بجانب ${iso(d.water)}` : ''}`
    if (d.kind === 'water') return `اتبع الممر بجانب ${iso(d.water)}`
    if (d.kind === 'pass') return `ستمرّ بجانب ${iso(d.building)} على ${d.side === 'left' ? 'يسارك' : 'يمينك'}`
    return null
  },
  spoken: (detail, words) => `${detail}. ${words}`,
  arCard(c) {
    if (c.kind === 'past') return `تابع مباشرةً مرورًا بجانب ${iso(c.place)} · ${c.away}`
    if (c.kind === 'continue') return `تابع مباشرةً ${c.away}`
    if (c.kind === 'arrive') return `${iso(c.label)} بعد ${c.away}`
    if (c.landmark) return `${TURN[c.type]} عند ${iso(c.landmark)} · ${c.now ? 'الآن' : c.away}`
    return c.now ? `${TURN[c.type]} الآن` : `${TURN[c.type]} بعد ${c.away}`
  },
  arStep: (type, landmark) => `${TURN[type]}${landmark ? ` عند ${iso(landmark)}` : ''}`,
}

