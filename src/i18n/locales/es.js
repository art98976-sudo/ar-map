import {formatNumber} from '../i18n.js'

const GIRA = {left: 'gira a la izquierda', right: 'gira a la derecha', 'slight-left': 'gira ligeramente a la izquierda', 'slight-right': 'gira ligeramente a la derecha'}
const GIRA_AHORA = {left: 'gira ahora a la izquierda', right: 'gira ahora a la derecha', 'slight-left': 'gira ahora ligeramente a la izquierda', 'slight-right': 'gira ahora ligeramente a la derecha'}
const LUEGO = {left: 'a la izquierda', right: 'a la derecha', 'slight-left': 'ligeramente a la izquierda', 'slight-right': 'ligeramente a la derecha'}
const capital = (text) => text.charAt(0).toUpperCase() + text.slice(1)
const distance = (m) => (m >= 1000 ? `${formatNumber(m / 1000, {decimals: 1})} km` : `${m <= 20 ? Math.round(m) : Math.round(m / 5) * 5} m`)
const via = (info) => (info ? (info.beside ? `por el camino junto a ${info.road}` : `por ${info.road}`) : null)
/** " en The Bite", " por Pathfoot Road", " en dirección a Library". */
const where = (m) => {
  const road = via(m?.ontoInfo)
  return (m?.landmark ? ` en ${m.landmark}` : '') + (road && !m.then ? ` ${road}` : '') + (m?.towards && !m.then ? ` en dirección a ${m.towards}` : '')
}
/** ", y 20 m después, a la izquierda por Pathfoot Road". */
const luego = (m) => {
  if (!m.then) return ''
  const otra = m.then.type === m.type ? 'otra vez ' : ''
  const road = via(m.ontoInfo)
  return `, y ${distance(m.then.gapM)} después, ${otra}${LUEGO[m.then.type]}${where(m.then)}${road ? ` ${road}` : ''}${m.towards ? ` en dirección a ${m.towards}` : ''}`
}

export const DIRECTIONS = {
  distance,
  place: (name) => name,
  onto: via,
  banner(m, away, arriveLabel) {
    if (m.type === 'arrive') return away == null ? `Has llegado a ${arriveLabel}` : `En ${away}, llegarás a ${arriveLabel}`
    if (away == null) return `${capital(GIRA_AHORA[m.type] ?? 'sigue recto')}${where(m)}${luego(m)}`
    return `En ${away}, ${GIRA[m.type] ?? 'sigue recto'}${where(m)}${luego(m)}`
  },
  stepLine(m, arriveLabel) {
    if (m.type === 'arrive') return `Llega a ${arriveLabel}`
    return `${capital(GIRA[m.type] ?? 'sigue recto')}${where(m)}${luego(m)}`
  },
  detail(d) {
    if (!d) return null
    if (d.kind === 'follow') return `Sigue ${d.beside ? `el camino junto a ${d.road}` : `por ${d.road}`}${d.water ? `, pasando junto a ${d.water}` : ''}`
    if (d.kind === 'water') return `Sigue el camino junto a ${d.water}`
    if (d.kind === 'pass') return `Pasa junto a ${d.building}, que queda a tu ${d.side === 'left' ? 'izquierda' : 'derecha'}`
    return null
  },
  spoken: (detail, words) => `${detail}. ${words}`,
  arCard(c) {
    if (c.kind === 'past') return `Sigue recto pasando ${c.place} · ${c.away}`
    if (c.kind === 'continue') return `Sigue recto ${c.away}`
    if (c.kind === 'arrive') return `${c.label} en ${c.away}`
    const words = capital(GIRA[c.type])
    if (c.landmark) return `${words} en ${c.landmark} · ${c.now ? 'ahora' : c.away}`
    return c.now ? capital(GIRA_AHORA[c.type]) : `${words} en ${c.away}`
  },
  arStep: (type, landmark) => `${capital(GIRA[type])}${landmark ? ` en ${landmark}` : ''}`,
}

